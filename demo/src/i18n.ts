export const strings: Record<Lang, Record<Key, string>> = { en, es };

export function t(lang: Lang, key: Key, values: Record<string, string | number> = {}): string {
  return strings[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}

export function detectLang(languages: readonly string[]): Lang {
  const first = languages[0]?.toLowerCase() ?? "en";
  return first.startsWith("es") ? "es" : "en";
}
