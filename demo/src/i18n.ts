export const strings: Record<Lang, Record<Key, string>> = { es, en };

export function t(lang: Lang, key: Key, values: Record<string, string | number> = {}): string {
  return strings[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}

export function isLang(value: unknown): value is Lang {
  return value === "es" || value === "en";
}

/**
 * Spanish is the default. A stored choice wins; a `lang` query value lets a link open the
 * English version directly. The browser language is not consulted.
 */
export function resolveLang(stored: string | null, query: string | null): Lang {
  if (isLang(query)) return query;
  if (isLang(stored)) return stored;
  return DEFAULT_LANG;
}
